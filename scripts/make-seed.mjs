// Generates supabase/seed.sql from data/*.json so the database starts with the same schemes and documents as the site.
// Usage: node scripts/make-seed.mjs   (then run supabase/seed.sql in the Supabase SQL editor, after schema.sql)
import { readFile, writeFile } from "node:fs/promises";

const q = (v) => (v === null || v === undefined ? "null" : `'${String(v).replace(/'/g, "''")}'`);
const arr = (a) => (a.length ? `array[${a.map(q).join(",")}]::text[]` : "'{}'::text[]");
const json = (o) => `${q(JSON.stringify(o))}::jsonb`;

const schemes = JSON.parse(await readFile("data/schemes.json", "utf8"));
const docs = JSON.parse(await readFile("data/documents.json", "utf8"));

const out = ["-- Generated by scripts/make-seed.mjs – do not edit by hand.", "begin;"];
for (const d of docs) {
  out.push(
    `insert into public.documents (id,name_ta,name_en,official_url) values (${q(d.id)},${q(d.name.ta)},${q(d.name.en)},${q(d.url)}) ` +
      `on conflict (id) do update set name_ta=excluded.name_ta,name_en=excluded.name_en,official_url=excluded.official_url;`,
  );
}
for (const s of schemes) {
  out.push(
    `insert into public.schemes (id,level,category,title_ta,title_en,department_ta,department_en,benefit_ta,benefit_en,eligibility_json,documents_json,apply_method_ta,apply_method_en,official_url,needs,keywords,popularity,status,last_verified_at) values (` +
      [q(s.id), q(s.level), q(s.category), q(s.title.ta), q(s.title.en), q(s.dept.ta), q(s.dept.en), q(s.benefit.ta), q(s.benefit.en), json(s.elig), json(s.docs), q(s.apply.ta), q(s.apply.en), q(s.url), arr(s.needs), arr(s.keywords), s.popularity, q(s.status), q(s.lastVerified)].join(",") +
      `) on conflict (id) do update set level=excluded.level,category=excluded.category,title_ta=excluded.title_ta,title_en=excluded.title_en,department_ta=excluded.department_ta,department_en=excluded.department_en,benefit_ta=excluded.benefit_ta,benefit_en=excluded.benefit_en,eligibility_json=excluded.eligibility_json,documents_json=excluded.documents_json,apply_method_ta=excluded.apply_method_ta,apply_method_en=excluded.apply_method_en,official_url=excluded.official_url,needs=excluded.needs,keywords=excluded.keywords,popularity=excluded.popularity,status=excluded.status,last_verified_at=excluded.last_verified_at;`,
  );
}
out.push("commit;");
await writeFile("supabase/seed.sql", out.join("\n") + "\n");
console.log(`seed.sql: ${docs.length} documents, ${schemes.length} schemes`);
